export function getRecommendedLearningPlan(age: number): MathLearningConfig {
  const bracket = getAgeBracket(age);
  switch (bracket) {
    case "4-5":
      return { ...PLAN_4_5 };
    case "6-7":
      return { ...PLAN_6_7 };
    case "8-9":
      return { ...PLAN_8_9 };
    case "10-12":
      return { ...PLAN_10_12 };
  }
}
